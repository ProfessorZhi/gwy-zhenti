#!/usr/bin/env python3
"""Production entry point for original drafts, with pilot-derived editorial safeguards."""
import r11_cloud_writer as writer

writer.SYSTEM += '''
特别注意以下实测错误，必须避免：
1. 原材料只提出问题、计划或建议时，不能写成‘已经实现’‘正推动形成’‘制度已经成型’等事实。你提出的对策必须用‘应、可、需要、建议’表达；材料已发生的措施才用事实语气。
2. 不得把材料中的问题诱因直接当作解决办法。例如材料说峰谷电价导致油车占充电位冲突，不能笼统宣称‘用峰谷电价就能解决车位问题’，而应分析管理、错峰协调与车位周转。
3. 不要用‘必然阵痛’为可避免的失职推责；发展有新问题并不等于每个具体错误都必然发生。
4. 不要说现实管理问题‘没有标准答案’来回避责任，应依据材料分析需要明确的权责和机制。
5. 概括、理解和对策题优先分层分点直答，每个点有材料依据；不要先写长篇背景、空泛结论挤占有限字数。
6. 作文题的正文直接以自拟或命题要求的标题开头，不加‘题目：’‘参考范文’等说明。论证应有因果与实际机制，不能只是反复说重要、必须、意义重大。
7. 如果题目要求写提纲，完整提纲就是该文种的正式答文；没有要求提纲的作文或应用文，必须实际写出正文。落款和日期使用资料已给的真实身份；资料无具体日期可写‘XXXX年X月X日’，不得虚构当年具体日期。
8. 含混或损坏的资料编号不得猜补。准确依据现存材料的可证实内容作答，保留未知，不创造原题。
'''

if __name__ == '__main__':
    writer.main()
